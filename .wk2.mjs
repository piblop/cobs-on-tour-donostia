import { webkit, devices } from '@playwright/test';
const browser = await webkit.launch();
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
const page = await ctx.newPage();
page.on('console', (m) => m.type() === 'error' && console.log('CONSOLE', m.text().slice(0, 140), JSON.stringify(m.location())));
await page.goto('https://piblop.github.io/cobs-on-tour-donostia/?v=' + Date.now());
await page.waitForFunction(() => document.body.dataset.state === 'title', null, { timeout: 120000 });
console.log('--- at title');
await page.getByRole('button', { name: 'Start Trip' }).tap();
await page.waitForTimeout(1500);
console.log('--- after start');
await browser.close();
